def rows(rs):
    return '\n    '.join('<tr>' + ''.join(f'<td class="l">{c}</td>' for c in r) + '</tr>' for r in rs)
def exsteps(rs):
    out = ['<table class="tight"><tr><th class="l">항목</th><th class="l">산출</th></tr>']
    for i, (q, a) in enumerate(rs):
        out.append(f'<tr><td class="l">{q}</td><td class="l"><span class="step" data-g="e{i}">{a}</span></td></tr>')
    out.append('</table>')
    return '\n      '.join(out)
def bars(t15, r15, t22, r22):
    k = 240 / t15
    w = lambda v: f'{v*k:.1f}'
    return {'BAR15': w(t15), 'BARR15': w(r15), 'BAR22': w(t22), 'BARR22': w(r22),
            'LX15': f'{94+t15*k+12:.1f}', 'LX22': f'{94+t22*k+12:.1f}',
            'TOT15': str(t15), 'REQ15': str(r15), 'TOT22': str(t22), 'REQ22': str(r22)}
def cards(cs, cls='card'):
    return '\n    '.join(f'<div class="{cls}"><h3>{h}</h3><p class="f21">{p}</p></div>' for h, p in cs)
def chips(cs):
    return '\n    '.join(f'<button class="chk">{c}</button>' for c in cs)

