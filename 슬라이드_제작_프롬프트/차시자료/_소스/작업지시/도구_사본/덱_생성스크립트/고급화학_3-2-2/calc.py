def parse(side):
    tot={}
    for term in side.split(' + '):
        term=term.strip(); m=re.match(r'^(\d+)?\s*(.*)$',term); c=int(m.group(1)) if m.group(1) else 1
        f=re.sub(r'\((s|l|g|aq)\)','',m.group(2))
        for a,n in re.findall(r'([A-Z][a-z]?)(\d*)',f): tot[a]=tot.get(a,0)+c*int(n or 1)
    return tot
