# ── 물 (IAPWS) ──
def h2o_vap(T):   # 포화 증기압 atm, Wagner–Pruss
    Tc,pc=647.096,22.064e6; t=1-T/Tc
    a=(-7.85951783,1.84408259,-11.7866497,22.6807411,-15.9618719,1.80122502)
    e=(1,1.5,3,3.5,4,7.5)
    return pc*exp(Tc/T*sum(ai*t**ei for ai,ei in zip(a,e)))/ATM
def h2o_sub(T):   # 얼음 승화 압력 atm (IAPWS 2011)
    Tt,pt=273.16,611.657; th=T/Tt
    a=(-0.212144006e2,0.273203819e2,-0.610598130e1); b=(0.333333333e-2,1.20666667,1.70333333)
    return pt*exp(sum(ai*th**bi for ai,bi in zip(a,b))/th)/ATM
def h2o_melt_T(P_atm):   # 얼음 Ih 융해 곡선: 압력 → 온도(K) (IAPWS, 이분법)
    Tt,pt=273.16,611.657
    def p(T): th=T/Tt; return pt*(1-0.626e6*(1-th**-3)+0.197135e6*(1-th**21.2))/ATM
    lo,hi=251.2,273.16
    for _ in range(80):
        m=(lo+hi)/2
        if p(m)>P_atm: lo=m
        else: hi=m
    return (lo+hi)/2
# ── 이산화 탄소 (Span–Wagner 보조식) ──
CO2_Tt,CO2_pt=216.592,0.51795e6
def co2_vap(T):
    Tc,pc=304.1282,7.3773e6; t=1-T/Tc
    a=(-7.0602087,1.9391218,-1.6463597,-3.2995634); e=(1,1.5,2,4)
    return pc*exp(Tc/T*sum(ai*t**ei for ai,ei in zip(a,e)))/ATM
def co2_sub(T):
    t=1-T/CO2_Tt
    return CO2_pt*exp(CO2_Tt/T*(-14.740846*t+2.4327015*t**1.9-5.3061778*t**2.9))/ATM
def co2_melt(T):
    x=T/CO2_Tt-1
    return CO2_pt*(1+1955.539*x+2055.4593*x*x)/ATM
